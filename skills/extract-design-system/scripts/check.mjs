for (const g of groups) if (g !== 'Other' && !has.has(`assets/${g}/README.md`)) W(`assets/${g}`, 'no README.md: name each file, where it is used, and a single-ink mark\'s ink');
for (const p of uploads) {
  if (/\.svg$/i.test(p) && size(p) > 2 * 1024 * 1024) E(p, 'SVG over 2 MB');
  else if (size(p) > 20 * 1024 * 1024) E(p, 'over 20 MB');
}

let index = null;
const unrecorded = [];
if (has.has('design-system.json')) {
  try { index = JSON.parse(text('design-system.json')); } catch (e) { E('design-system.json', `invalid JSON: ${e.message}`); }
}
if (index) {
  const w = 'design-system.json';
  if (index.v !== 3 || index.layout !== 'files') E(w, 'needs "v": 3 and "layout": "files"');
  if (!index.createdOnFiles && !index.convertedFrom) E(w, 'no createdOnFiles marker: the page opens it read-only');
  if (!index.title) E(w, 'no title: nothing names the system');
  if (!Array.isArray(index.libraries)) W(w, '"libraries" should be a list ([] for none)');
  for (const k of ['sections', 'blobs']) if (typeof index[k] !== 'object' || index[k] === null) W(w, `"${k}" should be {}`);
  if (index.docs?.readme !== 'project/README.md') W(w, 'docs should be {"readme": "project/README.md", "sections": []}');
  if (!index.lastChange?.by || !index.lastChange?.at) W(w, 'set lastChange {by, at, via, note}');
  for (const g of groups) if (!(index.groups ?? []).includes(g)) W(w, `asset group "${g}" is missing from "groups"`);
  for (const p of uploads) {
    const g = groupOf(p);
    const name = g === 'Other' ? p.slice('assets/'.length) : p.split('/').slice(2).join('/');
    const key = name.replace(/[^A-Za-z0-9_./-]/g, (ch) => [...Buffer.from(ch)].map((b) => `~${b.toString(16).padStart(2, '0')}`).join(''));
    if (!index.assetGroups?.[g]?.files?.[key]?.blob) unrecorded.push({ p, g, key });
  }
  if (unrecorded.length) (wantMap ? E : W)('design-system.json', `${unrecorded.length} asset(s) with no upload record: ${unrecorded.map((u) => `assets/${u.g}… files["${u.key}"]`).slice(0, 6).join(', ')}`);
} else if (has.has('design-system.json') === false) {
  (wantMap ? E : W)('design-system.json', 'not written yet: upload the assets, then write it last');
}

// ---------- report ----------
const out = wantMap ? console.error : console.log;
out(`checked ${proj}: ${all.length} files, ${colorTok.size} colours × ${themeIds.length || 0} theme(s), ${compDirs.length} component folders, ${uploads.length} asset upload(s)`);
out(`contrast: ${pairsChecked} pair×theme checks${pairsUnparsed ? `, ${pairsUnparsed} skipped (lab/lch/color() or unresolved)` : ''}`);
if (errors.length) { out(`\nERRORS (${errors.length}) — the page would drop or refuse these:`); for (const e of errors) out(`  ✗ ${e}`); }
if (warns.length) { out(`\nWARNINGS (${warns.length}):`); for (const w of warns) out(`  ! ${w}`); }
if (!wantMap && uploads.length && !index) out(`\nUPLOAD these to the system's url as assets (Artifact publish, asset: true, ≤25 per call):\n${uploads.map((p) => `  ${path.join(proj, p)}`).join('\n')}`);
out(errors.length ? '\nFAIL' : '\nOK');

if (wantMap) {
  if (errors.length) process.exit(1);
  const uploadSet = new Set(uploads);
  const files = all
    .filter((p) => p !== 'design-system.json' && !uploadSet.has(p) && p !== 'manifest.json' && !p.startsWith('api/'))
    .map((p) => `project/${p}`);
  const chunks = [];
  for (let i = 0; i < files.length; i += 254) chunks.push(files.slice(i, i + 254));
  if (!chunks.length) chunks.push([]);
  const calls = chunks.map((ch, i) => {
    const last = i === chunks.length - 1;
    const first = last ? 'project/design-system.json' : ch[0];
    const rest = last ? ch : ch.slice(1);
    return { root: dir, file_path: path.join(dir, first), files: Object.fromEntries(rest.map((p) => [p, p])) };
  });
  console.log(JSON.stringify({ calls }, null, 2));
}
process.exit(errors.length ? 1 : 0);
