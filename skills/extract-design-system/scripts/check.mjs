#!/usr/bin/env node
// Check a Design System folder (<dir>/project/…) against the Design System type's format before publishing:
// tokens.json values the page would silently drop, contrast of text/ground pairs in every theme, component
// previews and READMEs, the cover, fonts, assets and the index. With --map, print the upload and publish calls.
import fs from 'node:fs';
import path from 'node:path';
import { LENGTH, composite, contrast, isColorSyntax, parseColor } from './lib.mjs';

const USAGE = `Usage: node check.mjs <dir> [--map]
  <dir>   the folder holding project/ (project/README.md, project/tokens.json, project/components/…)
  --map   with no errors, print the asset uploads and the publish calls (index last) as JSON`;
const args = process.argv.slice(2);
if (!args.length || args.includes('-h') || args.includes('--help')) { console.log(USAGE); process.exit(args.length ? 0 : 2); }
const wantMap = args.includes('--map');
const dir = path.resolve(args.find((a) => !a.startsWith('--')));
const proj = path.join(dir, 'project');
if (!fs.existsSync(proj)) { console.error(`No project/ folder in ${dir}`); process.exit(2); }

const errors = [];
const warns = [];
const E = (w, m) => errors.push(`${w}: ${m}`);
const W = (w, m) => warns.push(`${w}: ${m}`);

// ---------- files and paths ----------
const all = [];
(function walk(rel) {
  for (const e of fs.readdirSync(path.join(proj, rel), { withFileTypes: true })) {
    const p = rel ? `${rel}/${e.name}` : e.name;
    if (e.isSymbolicLink()) E(p, 'a symlink: copy the real file');
    else if (e.isDirectory()) walk(p);
    else if (e.isFile()) all.push(p);
  }
})('');
const has = new Set(all);
const size = (p) => fs.statSync(path.join(proj, p)).size;
const text = (p) => fs.readFileSync(path.join(proj, p), 'utf8');

const TOOLCHAIN = /^(package\.json|package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|bunfig\.toml|tsconfig(\..+)?\.json|deno\.jsonc?|CLAUDE\.md|AGENTS\.md)$/;
let total = 0;
for (const p of all) {
  const segs = p.split('/');
  const name = segs.at(-1);
  if (segs.some((s) => s.startsWith('.')) && name !== '.image-slots.state.json') E(p, 'dot-files are refused');
  if (segs.includes('node_modules') || TOOLCHAIN.test(name)) E(p, 'toolchain and agent files are refused');
  if (/~\d/.test(name)) E(p, '8.3-style names are refused');
  if (/^(index\.html|SKILL\.md)$/.test(p) || p.startsWith('artifact-type/')) E(p, 'this path belongs to the type, not the system');
  if (p.startsWith('api/')) W(p, 'api/ cards are generated by the page: do not write them');
  if (p === 'manifest.json') W(p, 'generated by the page: do not write it');
  if (p === 'tokens.css' && !/generated from tokens\.json \*\//.test(text(p).split('\n')[0])) W(p, 'generated by the page; a hand-written one needs line 1 "/* <title> — generated from tokens.json */"');
  const s = size(p);
  total += s;
  if (s > 15 * 1024 * 1024) E(p, 'over 15 MiB');
}
if (all.length > 4080) E('project/', `${all.length} files (max 4,080)`);
if (total > 256 * 1024 * 1024) E('project/', 'over 256 MiB');

// ---------- README ----------
if (!has.has('README.md')) E('README.md', 'missing: every system needs its brand book');
else {
  const r = text('README.md');
  if (/^\s*#\s/.test(r)) W('README.md', 'starts with a # title: the page already shows the name; open with what the product is');
  if (size('README.md') > 200 * 1024) E('README.md', 'over 200 KB');
  if (r.trim().split(/\s+/).length < 150) W('README.md', 'under 150 words: a codebase earns sections (content fundamentals, visual foundations, iconography, components)');
}
const sections = all.filter((p) => /\.mdx?$/.test(p) && p !== 'README.md' && !/^(components|archived|assets|fonts)\//.test(p));
if (sections.length > 24) W('*.md', `${sections.length} extra sections; the page shows 24`);

// ---------- tokens.json ----------
const NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$/;
const isLen = (v) => typeof v === 'number' || (typeof v === 'string' && (LENGTH.test(v.trim()) || v.trim() === '0'));
const balanced = (s) => { let d = 0; for (const c of s) { if (c === '(') d++; else if (c === ')' && --d < 0) return false; } return d === 0; };
const known = new Set();
const colorTok = new Map();
const noUsage = [];
let themeIds = [];
let tokens = null;
if (!has.has('tokens.json')) W('tokens.json', 'missing: fine only when the README is the whole system');
else {
  try { tokens = JSON.parse(text('tokens.json')); } catch (e) { E('tokens.json', `invalid JSON: ${e.message}`); }
  if (size('tokens.json') > 512 * 1024) E('tokens.json', 'over 512 KB');
}

const valueIn = (tok, id) => {
  const v = tok.value;
  if (v === null || typeof v !== 'object') return v;
  return v[id] ?? v[themeIds[0]] ?? Object.values(v)[0] ?? null;
};
function resolveColor(n, id, depth = 0) {
  if (depth > 16) return undefined;
  const tok = colorTok.get(n);
  if (!tok) return null;
  const v = valueIn(tok, id);
  if (typeof v !== 'string') return null;
  const a = v.match(/^\{([^}]+)\}$/);
  if (!a) return v;
  return a[1] === n ? undefined : resolveColor(a[1], id, depth + 1);
}

function checkValue(fam, tok, w) {
  const perTheme = tok.value !== null && typeof tok.value === 'object';
  if (perTheme && fam !== 'shadow') W(w, 'per-theme values apply only to colour and shadow');
  for (const v of perTheme ? Object.values(tok.value) : [tok.value]) {
    if (fam === 'spacing' || fam === 'radius') {
      if (!isLen(v)) E(w, `"${v}" is not a length (px, rem, em, % or a number): it drops`);
    } else if (fam === 'shadow') {
      if (typeof v !== 'string' || v.length > 400 || /var\(|url\(|calc\(|color-mix/i.test(v)) E(w, `"${v}" is not a box-shadow the page reads (no var(), url(), calc(); ≤400 chars)`);
    } else if (typeof v !== 'number' && (typeof v !== 'string' || !/^[A-Za-z0-9 #%(),./+_-]{1,200}$/.test(v) || /url\(|var\(/i.test(v) || !balanced(v))) {
      E(w, `"${v}" is not a plain CSS value: it drops`);
    }
  }
}

if (tokens) {
  const RESERVED = new Set(['name', 'version', 'meta', 'description', '$schema']);
  const famNames = new Map();
  const extra = Object.keys(tokens).filter((k) => !RESERVED.has(k) && !['color', 'type', 'spacing', 'radius', 'shadow'].includes(k));
  if (extra.length > 12) W('tokens.json', `${extra.length} extra families (max 12)`);
  for (const [fam, val] of Object.entries(tokens)) {
    if (RESERVED.has(fam) || fam === 'type') continue;
    const w = `tokens.json ${fam}`;
    if (!val || typeof val !== 'object' || !Array.isArray(val.tokens)) { E(w, 'not a {"tokens":[…]} list: the page shows it empty (a DTCG name→value map is unreadable)'); continue; }
    if (/^(motion|animation|duration|easing|transition)s?$/i.test(fam)) W(w, 'the type has no motion family: describe motion in the README');
    if (fam === 'color') {
      const th = Array.isArray(val.themes) && val.themes.length ? val.themes : [{ id: 'light' }];
      themeIds = th.map((x) => x?.id);
      if (themeIds.length > 8) E(w, 'more than 8 themes');
      for (const id of themeIds) if (!/^[a-z0-9][a-z0-9_.-]{0,63}$/.test(id ?? '')) E(w, `theme id "${id}" is not a lowercase name`);
      if (val.tokens.length > 600) E(w, `${val.tokens.length} colours (max 600)`);
    } else if (val.tokens.length > 60) E(w, `${val.tokens.length} tokens (max 60)`);
    for (const tok of val.tokens) {
      const n = typeof tok?.name === 'string' ? tok.name.replace(/^--/, '') : tok?.name;
      const tw = `${w} "${n}"`;
      if (typeof n !== 'string' || !NAME.test(n)) { E(tw, 'name must match [A-Za-z0-9][A-Za-z0-9_.-]{0,63} (no spaces or /): it drops'); continue; }
      if (famNames.has(n)) { E(tw, `same name as a ${famNames.get(n)} token: the second drops`); continue; }
      famNames.set(n, fam);
      known.add(n);
      if (!tok.usage) noUsage.push(n);
      else if (String(tok.usage).length > 1000) W(tw, 'usage over 1,000 characters is clamped');
      if (fam === 'color') colorTok.set(n, tok);
      else checkValue(fam, tok, tw);
    }
  }
  for (const [n, tok] of colorTok) {
    const tw = `tokens.json color "${n}"`;
    const vals = tok.value !== null && typeof tok.value === 'object' ? tok.value : { [themeIds[0]]: tok.value };
    let ok = 0;
    for (const [id, v] of Object.entries(vals)) {
      if (!themeIds.includes(id)) W(tw, `value for unknown theme "${id}"`);
      const alias = typeof v === 'string' && v.match(/^\{([^}]+)\}$/);
      if (alias) {
        if (alias[1] === n) E(tw, `${id}: aliases itself: it drops`);
        else if (!colorTok.has(alias[1])) E(tw, `${id}: {${alias[1]}} names no colour token: it drops`);
        else ok++;
      } else if (isColorSyntax(v)) ok++;
      else E(tw, `${id}: "${v}" is not a colour the page reads (hex; rgb()/hsl()/oklch()… with plain numbers; {alias}): it drops`);
    }
    if (!ok) E(tw, 'no valid value in any theme: the token drops');
    for (const id of themeIds) if (resolveColor(n, id) === undefined) E(tw, `${id}: alias cycle or a chain deeper than 16`);
  }

  const ty = tokens.type;
  if (ty !== undefined) {
    const w = 'tokens.json type';
    const fams = ty?.families ?? {};
    for (const [k, stack] of Object.entries(fams)) {
      if (!/^[a-z0-9][a-z0-9_.-]{0,63}$/i.test(k)) E(`${w} families.${k}`, 'bad key');
      if (typeof stack !== 'string' || stack.length > 200 || /[;{}<>\\()]/.test(stack) || (stack.match(/"/g) ?? []).length % 2 || (stack.match(/'/g) ?? []).length % 2) {
        E(`${w} families.${k}`, 'not a plain font stack (≤200 chars; no ; { } < > \\ ( ); balanced quotes)');
      }
      known.add(`font-${k.toLowerCase()}`);
    }
    const groups = ty?.groups ?? [];
    let nStyles = 0;
    if (!Array.isArray(groups)) E(w, 'groups must be a list');
    else {
      if (groups.length > 12) E(w, 'more than 12 groups');
      for (const g of groups) {
        const gw = `${w} group "${g?.name}"`;
        if (!Array.isArray(g?.styles)) { E(gw, 'styles must be a list'); continue; }
        if (g.family && !(g.family in fams)) W(gw, `family "${g.family}" is not a key of type.families`);
        for (const s of g.styles) {
          nStyles++;
          const sw = `${gw} style "${s?.name}"`;
          if (!NAME.test(s?.name ?? '')) E(sw, 'bad name: it drops');
          if (!isLen(s?.fontSize)) E(sw, `fontSize "${s?.fontSize}" is not a length: the style drops`);
          const lh = s?.lineHeight;
          if (lh !== undefined && !(typeof lh === 'number' ? lh > 0 && lh < 10 : isLen(lh) || (/^\d*\.?\d+$/.test(String(lh)) && Number(lh) < 10))) E(sw, `lineHeight "${lh}" is not a length or a unitless number under 10`);
          if (s?.fontWeight !== undefined && !/^(\d{1,4}(\s+\d{1,4})?|normal|bold)$/.test(String(s.fontWeight))) E(sw, 'fontWeight must be 1–1000 or "300 800"');
          if (s?.letterSpacing !== undefined && !isLen(s.letterSpacing)) E(sw, 'letterSpacing is not a length');
          if (s?.family && !(s.family in fams)) W(sw, `family "${s.family}" is not a key of type.families`);
          if (!s?.usage) noUsage.push(`type:${s?.name}`);
        }
      }
      if (nStyles > 80) E(w, `${nStyles} styles (max 80)`);
    }
    if (!nStyles) W(w, 'no type styles: name the real ones (page-title, body, label…) from how the UI sets text');
    const listed = new Set();
    for (const f of ty?.fonts ?? []) {
      const fw = `${w} font "${f?.family}"`;
      const file = f?.file?.includes('/') ? f.file : `fonts/${f?.file}`;
      listed.add(file);
      if (!f?.family || /["']/.test(f.family)) E(fw, 'family must be a bare name, no quotes');
      if (!f?.file || !has.has(file)) E(fw, `file ${f?.file} is not under project/`);
      if (f?.weight && !/^\d{1,4}(\s+\d{1,4})?$/.test(String(f.weight))) E(fw, 'weight must be "400" or "300 800"');
      if (f?.style && !/^(normal|italic|oblique)$/.test(f.style)) E(fw, 'style must be normal, italic or oblique');
    }
    for (const p of all.filter((x) => x.startsWith('fonts/'))) {
      if (!listed.has(p)) W(p, 'not listed in tokens.json type.fonts, so no @font-face is made');
      if (size(p) > 1024 * 1024) W(p, 'over 1 MB');
    }
  }
  if (noUsage.length) W('tokens.json', `${noUsage.length} without a usage note: ${noUsage.slice(0, 25).join(', ')}${noUsage.length > 25 ? ' …' : ''}`);
}

// ---------- contrast ----------
function groundsIn(u) {
  const out = [];
  const re = /\bon\s+/gi;
  let m;
  while ((m = re.exec(u))) {
    let rest = u.slice(m.index + m[0].length);
    for (;;) {
      const t = rest.match(/^(?:\s*(?:,|&|\/|\band\b|\bor\b)\s*)*(?:the\s+)?`?([A-Za-z0-9][A-Za-z0-9_.-]*)`?/);
      if (!t) break;
      const name = colorTok.has(t[1]) ? t[1] : t[1].replace(/\.+$/, '');
      if (!colorTok.has(name)) break;
      out.push(name);
      rest = rest.slice(t[0].length);
    }
  }
  return out;
}
let pairsChecked = 0;
let pairsUnparsed = 0;
if (colorTok.size && themeIds.length) {
  const pairs = new Map();
  const add = (fg, bg, why) => { if (fg !== bg && colorTok.has(fg) && colorTok.has(bg) && !pairs.has(`${fg}|${bg}`)) pairs.set(`${fg}|${bg}`, { fg, bg, why }); };
  for (const [n, tok] of colorTok) {
    if (n === 'foreground') add(n, 'background', 'name');
    if (n.endsWith('-foreground')) add(n, n.slice(0, -11), 'name');
    if (n.endsWith('-fg')) add(n, n.slice(0, -3), 'name');
    if (n.startsWith('on-')) add(n, n.slice(3), 'name');
    for (const g of groundsIn(String(tok.usage ?? ''))) add(n, g, 'usage');
  }
  for (const { fg, bg, why } of pairs.values()) {
    const u = String(colorTok.get(fg).usage ?? '');
    const min = /\b(icons?|borders?|rings?|focus|outlines?|dividers?|large|non-text|charts?|bars?|dots?|indicators?|24px)\b/i.test(u) ? 3 : 4.5;
    const flagged = /\b(fails?|below\s+(4\.5|3)|low[- ]contrast|decorative)\b/i.test(u);
    for (const id of themeIds) {
      const a = parseColor(resolveColor(fg, id) ?? '');
      const b = parseColor(resolveColor(bg, id) ?? '');
      if (!a || !b) { pairsUnparsed++; continue; }
      pairsChecked++;
      const base = /dark|night|dim/.test(id) ? { r: 0, g: 0, b: 0, a: 1 } : { r: 1, g: 1, b: 1, a: 1 };
      const { fg: f, bg: g } = composite(a, b, base);
      const r = contrast(f, g);
      if (r < min && !flagged) W(`contrast ${id}`, `${fg} on ${bg} is ${r.toFixed(2)}:1, under ${min}:1 (pair from its ${why === 'usage' ? 'usage note' : 'name'}); keep the source value and say so in the note`);
    }
  }
}

// ---------- components ----------
const HOSTS = /^https:\/\/(cdn\.jsdelivr\.net\/npm\/|unpkg\.com\/|cdnjs\.cloudflare\.com\/|cdn\.tailwindcss\.com\/|code\.jquery\.com\/|fonts\.googleapis\.com\/|fonts\.gstatic\.com\/)/;
const LITERAL_COLOR = /(?<![\w-])#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab)\(/;
const defined = new Set();
const definedIn = (s) => { for (const m of s.matchAll(/(--[\w-]+)\s*:/g)) defined.add(m[1].slice(2)); };
const undefinedVars = (s) => [...new Set([...s.matchAll(/var\(\s*--([\w-]+)/g)].map((m) => m[1]))].filter((v) => !known.has(v) && !defined.has(v));
const literalColors = (css) => css.split('\n').filter((l) => !/^\s*--[\w-]+\s*:/.test(l) && LITERAL_COLOR.test(l)).length;

if (has.has('components/bundle.css')) {
  const css = text('components/bundle.css');
  if (/<\/style/i.test(css)) E('components/bundle.css', 'contains "</style": it would break pages that inline it');
  if (size('components/bundle.css') > 2 * 1024 * 1024) E('components/bundle.css', 'over 2 MB');
  definedIn(css);
}
if (has.has('components/bundle.js')) {
  const js = text('components/bundle.js');
  if (/<\/script|<!--/i.test(js)) E('components/bundle.js', 'contains "</script" or "<!--"');
  if (size('components/bundle.js') > 6 * 1024 * 1024) E('components/bundle.js', 'over 6 MB');
  if (!/^\/\* @ds-bundle:/.test(js)) W('components/bundle.js', 'no line-1 /* @ds-bundle: {…} */ header (namespace and component order)');
}
if (has.has('components/bundle.css')) {
  const css = text('components/bundle.css');
  const u = undefinedVars(css);
  if (u.length) W('components/bundle.css', `var() names no token or stylesheet variable: ${u.slice(0, 8).join(', ')}`);
  const n = literalColors(css);
  if (n) W('components/bundle.css', `${n} line(s) with a literal colour: take colours from tokens (var(--…))`);
}

function checkUrl(p, u) {
  if (!HOSTS.test(u)) { W(p, `${u} will not load in a preview (only the artifact CDNs and Google Fonts)`); return; }
  if (/fonts\.(googleapis|gstatic)\.com/.test(u)) return;
  if (/@latest\b/.test(u) || /(jsdelivr\.net\/npm|unpkg\.com)\/(@[^/]+\/)?[^/@]+(\/|$)/.test(u) || /@\d+(\.\d+)?(\/|$)/.test(u) || /cdn\.tailwindcss\.com\/?$/.test(u)) {
    W(p, `${u}: pin an exact version (x.y.z)`);
  }
}
function checkPreview(p, cover) {
  const h = text(p);
  if (size(p) > 256 * 1024) E(p, 'over 256 KB');
  const m = h.split('\n')[0].match(/^<!--\s*@dsCard\b(.*?)-->/);
  if (!m) E(p, 'line 1 must be the marker <!-- @dsCard group="…" height=N -->');
  else {
    const raw = m[1].match(/height=["']?(\d+)/)?.[1];
    const [lo, hi] = cover ? [240, 360] : [40, 4000];
    if (!(Number(raw) >= lo && Number(raw) <= hi)) W(p, `height=${raw ?? '(none)'}: use ${lo}–${hi}`);
    if (!cover && !/group=/.test(m[1])) W(p, 'no group= in the marker: the card lands ungrouped');
  }
  if (/<(iframe|frame|object|embed|portal|noscript)\b/i.test(h)) E(p, 'iframe, frame, object, embed, portal and noscript are refused');
  for (const u of h.matchAll(/\b(?:src|href)\s*=\s*["'](https?:\/\/[^"']+)/gi)) checkUrl(p, u[1]);
  for (const u of h.matchAll(/@import\s+(?:url\()?["']?(https?:\/\/[^"')\s]+)/gi)) checkUrl(p, u[1]);
  const local = new Set([...h.matchAll(/(--[\w-]+)\s*:/g)].map((x) => x[1].slice(2)));
  const u = undefinedVars(h).filter((v) => !local.has(v));
  if (u.length) W(p, `var() names no token or stylesheet variable: ${u.slice(0, 8).join(', ')}`);
  const styles = [...h.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map((x) => x[1]).join('\n')
    + [...h.matchAll(/\bstyle\s*=\s*"([^"]*)"/gi)].map((x) => `\n${x[1]}`).join('');
  const lit = literalColors(styles) + [...h.matchAll(/\b(?:fill|stroke)\s*=\s*"#[0-9a-fA-F]{3,8}"/g)].length;
  if (lit) W(p, `${lit} literal colour(s): take colours from tokens (var(--…)) so both themes work`);
}

const compDirs = [...new Set(all.filter((p) => p.startsWith('components/') && p.split('/').length >= 3).map((p) => p.split('/')[1]))]
  .filter((c) => c !== 'lib' && c !== 'src');
for (const c of compDirs) {
  const w = `components/${c}`;
  const prev = `${w}/preview.html`;
  const readme = `${w}/README.md`;
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(c)) E(w, 'folder name must be an ASCII JS identifier');
  if (c === 'Cover') {
    if (all.some((p) => p.startsWith(`${w}/`) && p !== prev)) E(w, 'keep Cover/ bare (only preview.html), or it becomes an ordinary component');
  } else if (!has.has(readme)) W(w, 'no README.md: summary sentence, variants, what the consumer provides, don\'ts');
  if (has.has(readme) && size(readme) > 64 * 1024) E(readme, 'over 64 KB');
  if (has.has(prev)) checkPreview(prev, c === 'Cover');
  else W(w, 'no preview.html');
}
if (!has.has('components/Cover/preview.html')) W('components/Cover/preview.html', 'missing: write the cover last (the type\'s cover.md)');

